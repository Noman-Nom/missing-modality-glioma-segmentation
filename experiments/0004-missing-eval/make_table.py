"""The analysis CSVs of one eval folder -> four LaTeX files in writing/tables/ (spec 0004, AC-14).

    uv run python experiments/0004-missing-eval/make_table.py --eval <eval dir>
Writes 0004-missing-eval-<fold>-dice.tex, -hd95.tex, -marginal.tex and -heatmap.tex. No number is
typed by hand. Exit 1 if an analysis CSV is missing or has the wrong row count. The four files
compile through writing/tracer/e2-preview.tex.
"""
import argparse
import csv
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from common.data import MODALITIES, REGIONS
from common.missing import PATTERNS
from common.runlog import load_config, load_run

REPO = Path(__file__).resolve().parents[2]
OUT = REPO / "writing" / "tables"
NOTE = {
    "val": ("Development fold, not a test result. The checkpoint was chosen on this fold at "
            "complete input, so pattern 1 is slightly optimistic."),
    "test": "Test fold, opened once.",
}
METRICS = ("dice", "hd95_mm")
METRIC_LABEL = {"dice": "Dice", "hd95_mm": "HD95 (mm)"}
DECIMALS = {"dice": 3, "hd95_mm": 1}
STAR = "$^{*}$"
NODE_LABEL = (r"  nodes near coords={\pgfmathprintnumber[fixed,fixed zerofill,precision=3]"
              r"{\pgfplotspointmeta}},")


def read_rows(path, keys, expected):
    """A CSV as {key tuple: row}. Raises SystemExit if missing or on a wrong row count."""
    if not Path(path).is_file():
        raise SystemExit(f"ERROR: {path} missing")
    with open(path, newline="") as f:
        rows = {tuple(r[k] for k in keys): r for r in csv.DictReader(f)}
    if len(rows) != expected:
        raise SystemExit(f"ERROR: {len(rows)} rows in {Path(path).name}, expected {expected}")
    return rows


def read_stats(eval_dir):
    """stats.csv as {(metric, region, pattern_id): row}, pattern_id an int."""
    rows = read_rows(Path(eval_dir) / "stats.csv", ("metric", "region", "pattern_id"),
                     len(METRICS) * len(REGIONS) * len(PATTERNS))
    return {(m, g, int(p)): r for (m, g, p), r in rows.items()}


def read_marginal(eval_dir):
    """marginal.csv as {(metric, region, modality): row}."""
    return read_rows(Path(eval_dir) / "marginal.csv", ("metric", "region", "modality"),
                     len(METRICS) * len(REGIONS) * len(MODALITIES))


def star(row, alpha):
    """The significance star of a tested pattern. Pattern 1 has no p value, so no star."""
    return STAR if row["p_holm"] and float(row["p_holm"]) < alpha else ""


def interval(row, places):
    return f"[{float(row['ci_low']):.{places}f}, {float(row['ci_high']):.{places}f}]"


def dice_cells(row, alpha):
    """mean, mean_diff with its star, CI. Pattern 1 has no difference, so -- in both."""
    mean = f"{float(row['mean']):.3f}"
    if not row["mean_diff"]:
        return [mean, "--", "--"]
    return [mean, f"{float(row['mean_diff']):.3f}{star(row, alpha)}", interval(row, 3)]


def hd95_cells(row, alpha):
    """median with its star (HD95 leads with the median), mean, n_pred_empty."""
    return [f"{float(row['median']):.1f}{star(row, alpha)}", f"{float(row['mean']):.1f}",
            row["n_pred_empty"]]


def provenance(rec):
    return [f"% generated by experiments/0004-missing-eval/make_table.py from run {rec['eval_id']}",
            f"% config {rec['config_hash']}, git {rec['git_commit']}, seed {rec['seed']}. Do not edit."]


def caption(what, n, rec):
    return (rf"\caption{{{what}, {rec['fold']} fold, n = {n}, seed {rec['seed']}. "
            rf"{NOTE[rec['fold']]}}}")


def table(rec, n, what, name, columns, head, rows):
    """The shared booktabs layout. head and rows are lists of finished LaTeX lines."""
    return "\n".join([
        *provenance(rec),
        r"\begin{table}[htbp]",
        r"\centering",
        caption(what, n, rec),
        rf"\label{{tab:missing-eval-{rec['fold']}-{name}}}",
        r"\resizebox{\linewidth}{!}{%",
        rf"\begin{{tabular}}{{{columns}}}",
        r"\toprule",
        *head,
        r"\midrule",
        *rows,
        r"\bottomrule",
        r"\end{tabular}%",
        "}",
        r"\end{table}",
    ]) + "\n"


def region_head(span, first, sub):
    """The two header lines: one spanning label per region, then the column names."""
    regions = " & ".join(rf"\multicolumn{{{span}}}{{c}}{{{g}}}" for g in REGIONS)
    blank = " & ".join("" for _ in first)
    return [rf"{blank} & {regions} \\", " & ".join([*first, *sub * len(REGIONS)]) + r" \\"]


def pattern_table(stats, rec, alpha, metric, what, name, sub, cells):
    rows = []
    for p, pattern in PATTERNS.items():
        filled = [c for g in REGIONS for c in cells(stats[metric, g, p], alpha)]
        rows.append(" & ".join([str(p), pattern.name, *filled]) + r" \\")
    return table(rec, stats[metric, REGIONS[0], 1]["n"], what, name,
                 "rl" + "r" * len(sub) * len(REGIONS), region_head(len(sub), ["ID", "Present"], sub),
                 rows)


def dice_table(stats, rec, alpha):
    return pattern_table(stats, rec, alpha, "dice", "Dice under each missing modality pattern",
                         "dice", ["Mean", "Diff", "CI"], dice_cells)


def hd95_table(stats, rec, alpha):
    return pattern_table(stats, rec, alpha, "hd95_mm",
                         "HD95 in mm under each missing modality pattern", "hd95",
                         ["Median", "Mean", "Empty"], hd95_cells)


def marginal_table(marginal, stats, rec):
    rows = []
    for m in METRICS:
        places = DECIMALS[m]
        for modality in MODALITIES:
            cells = [c for g in REGIONS for c in (
                f"{float(marginal[m, g, modality]['mean_diff']):.{places}f}",
                interval(marginal[m, g, modality], places))]
            rows.append(" & ".join([METRIC_LABEL[m], modality, *cells]) + r" \\")
    return table(rec, stats["dice", REGIONS[0], 1]["n"],
                 "Marginal effect of each modality, present minus absent", "marginal",
                 "ll" + "rr" * len(REGIONS), region_head(2, ["Metric", "Modality"], ["Diff", "CI"]),
                 rows)


def heatmap(stats, rec):
    """A greyscale PGFPlots matrix of Dice mean_diff. Pattern 1 minus itself is 0 by definition."""
    fold = rec["fold"]
    values = {(g, p): float(stats["dice", g, p]["mean_diff"] or 0.0)
              for g in REGIONS for p in PATTERNS}
    # a scale needs two ends: with no drop at all (a toy run) the low end sits just below 0
    low = min(*values.values(), -0.001)
    lines = [f"{x} {y} {values[g, p]:.6f}" for y, p in enumerate(PATTERNS)
             for x, g in enumerate(REGIONS)]
    labels = ",".join(f"{{{p}: {pattern.name}}}" for p, pattern in PATTERNS.items())
    return "\n".join([
        *provenance(rec),
        r"\begin{figure}[htbp]",
        r"\centering",
        r"\begin{tikzpicture}",
        r"\begin{axis}[",
        r"  width=0.5\linewidth, height=0.9\textheight,",
        r"  colormap={e2grey}{gray(0cm)=(0.45); gray(1cm)=(1)},",
        rf"  colorbar, point meta min={low:.6f}, point meta max=0,",
        (rf"  colorbar style={{ytick={{{low:.6f},0}}, /pgf/number format/fixed, "
         r"/pgf/number format/precision=3},"),
        rf"  xtick={{0,...,{len(REGIONS) - 1}}}, xticklabels={{{','.join(REGIONS)}}},",
        rf"  ytick={{0,...,{len(PATTERNS) - 1}}}, yticklabels={{{labels}}},",
        r"  y dir=reverse, enlargelimits=false, tick style={draw=none},",
        NODE_LABEL,
        r"  nodes near coords align={center},",
        r"  every node near coord/.append style={font=\footnotesize, text=black},",
        "]",
        rf"\addplot[matrix plot*, mesh/cols={len(REGIONS)}, point meta=explicit]",
        r"  table[x index=0, y index=1, meta index=2] {",
        *lines,
        "};",
        r"\end{axis}",
        r"\end{tikzpicture}",
        caption("Dice difference from complete input, per pattern and region",
                stats["dice", REGIONS[0], 1]["n"], rec),
        rf"\label{{fig:missing-eval-{fold}-heatmap}}",
        r"\end{figure}",
    ]) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--eval", required=True, type=Path)
    ap.add_argument("--out-dir", type=Path, default=OUT)
    a = ap.parse_args(argv)
    rec = load_run(a.eval)
    alpha = load_config(a.eval / "config.toml")["eval"]["alpha"]
    stats, marginal = read_stats(a.eval), read_marginal(a.eval)
    files = {"dice": dice_table(stats, rec, alpha), "hd95": hd95_table(stats, rec, alpha),
             "marginal": marginal_table(marginal, stats, rec), "heatmap": heatmap(stats, rec)}
    a.out_dir.mkdir(parents=True, exist_ok=True)
    for name, tex in files.items():
        path = a.out_dir / f"0004-missing-eval-{rec['fold']}-{name}.tex"
        path.write_text(tex)
        print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
