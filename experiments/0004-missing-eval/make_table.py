"""stats.csv of one eval folder -> writing/tables/0004-missing-eval-<fold>-dice.tex (spec 0004).

    uv run python experiments/0004-missing-eval/make_table.py --eval <eval dir>
No number is typed by hand. Exit 1 if stats.csv is missing or has the wrong row count. The CI
column shows -- until the bootstrap lands with the full statistics milestone.
"""
import argparse
import csv
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from common.data import REGIONS
from common.missing import PATTERNS
from common.runlog import load_config, load_run

REPO = Path(__file__).resolve().parents[2]
OUT = REPO / "writing" / "tables"
NOTE = {
    "val": ("Development fold, not a test result. The checkpoint was chosen on this fold at "
            "complete input, so pattern 1 is slightly optimistic."),
    "test": "Test fold, opened once.",
}


def read_stats(eval_dir):
    """The Dice rows as {(region, pattern_id): row}. Raises SystemExit on a wrong row count."""
    path = Path(eval_dir) / "stats.csv"
    if not path.is_file():
        raise SystemExit(f"ERROR: {path} missing")
    with open(path, newline="") as f:
        rows = {(r["region"], int(r["pattern_id"])): r for r in csv.DictReader(f)
                if r["metric"] == "dice"}
    expected = len(PATTERNS) * len(REGIONS)
    if len(rows) != expected:
        raise SystemExit(f"ERROR: {len(rows)} Dice rows in stats.csv, expected {expected}")
    return rows


def dice_cells(row, alpha):
    """mean, mean_diff with its star, CI. Pattern 1 has no difference, so -- in both."""
    mean = f"{float(row['mean']):.3f}"
    if not row["mean_diff"]:
        return [mean, "--", "--"]
    star = "$^{*}$" if float(row["p_holm"]) < alpha else ""
    ci = f"[{float(row['ci_low']):.3f}, {float(row['ci_high']):.3f}]" if row["ci_low"] else "--"
    return [mean, f"{float(row['mean_diff']):.3f}{star}", ci]


def dice_table(rows, rec, alpha):
    n = rows[REGIONS[0], 1]["n"]
    fold = rec["fold"]
    head = " & ".join(rf"\multicolumn{{3}}{{c}}{{{g}}}" for g in REGIONS)
    sub = " & ".join(["Mean", "Diff", "CI"] * len(REGIONS))
    lines = [
        f"% generated by experiments/0004-missing-eval/make_table.py from run {rec['eval_id']}",
        f"% config {rec['config_hash']}, git {rec['git_commit']}, seed {rec['seed']}. Do not edit.",
        r"\begin{table}[htbp]",
        r"\centering",
        (rf"\caption{{Dice under each missing modality pattern, {fold} fold, n = {n}, "
         rf"seed {rec['seed']}. {NOTE[fold]}}}"),
        rf"\label{{tab:missing-eval-{fold}-dice}}",
        r"\resizebox{\linewidth}{!}{%",
        r"\begin{tabular}{rl" + "rrr" * len(REGIONS) + "}",
        r"\toprule",
        rf" & & {head} \\",
        rf"ID & Present & {sub} \\",
        r"\midrule",
    ]
    for p, pattern in PATTERNS.items():
        cells = [c for g in REGIONS for c in dice_cells(rows[g, p], alpha)]
        lines.append(" & ".join([str(p), pattern.name, *cells]) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}%", "}", r"\end{table}"]
    return "\n".join(lines) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--eval", required=True, type=Path)
    ap.add_argument("--out-dir", type=Path, default=OUT)
    a = ap.parse_args(argv)
    rec = load_run(a.eval)
    alpha = load_config(a.eval / "config.toml")["eval"]["alpha"]
    tex = dice_table(read_stats(a.eval), rec, alpha)
    a.out_dir.mkdir(parents=True, exist_ok=True)
    path = a.out_dir / f"0004-missing-eval-{rec['fold']}-dice.tex"
    path.write_text(tex)
    print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
