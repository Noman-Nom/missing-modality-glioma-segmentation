"""metrics.csv of one tracer run -> writing/tables/0002-tracer-bullet.tex (spec 0001, AC-12).

    uv run python experiments/0002-tracer-bullet/make_table.py --run <run dir>
Reads only the run's metrics.csv and run.json. No number is typed by hand.
"""
import argparse
import csv
import statistics
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from common.data import REGIONS
from common.missing import PATTERNS
from common.runlog import load_run

REPO = Path(__file__).resolve().parents[2]
OUT = REPO / "writing" / "tables" / "0002-tracer-bullet.tex"


def cell_stats(rows):
    """Dice mean, Dice median, HD95 mean, HD95 median, both empty count, one empty count.

    Both empty: truth and prediction empty (scored Dice 1). One empty: exactly one side empty
    (scored Dice 0).
    """
    dice = [float(r["dice"]) for r in rows]
    hd = [float(r["hd95_mm"]) for r in rows]
    n_empty = [(r["gt_empty"] == "True") + (r["pred_empty"] == "True") for r in rows]
    return (f"{statistics.mean(dice):.3f}", f"{statistics.median(dice):.3f}",
            f"{statistics.mean(hd):.1f}", f"{statistics.median(hd):.1f}",
            str(n_empty.count(2)), str(n_empty.count(1)))


def make(run_dir):
    rec = load_run(run_dir)
    n_val = len(rec["val_cases"])
    path = Path(run_dir) / "metrics.csv"
    if not path.is_file():
        raise SystemExit(f"ERROR: {path} missing")
    with open(path, newline="") as f:
        rows = list(csv.DictReader(f))
    expected = n_val * len(PATTERNS) * len(REGIONS)
    if len(rows) != expected:
        raise SystemExit(f"ERROR: {len(rows)} rows in metrics.csv, expected {expected}")

    lines = [
        f"% generated by experiments/0002-tracer-bullet/make_table.py from run {rec['run_id']}",
        f"% config {rec['config_hash']}, git {rec['git_commit']}, seed {rec['seed']}. Do not edit.",
        r"\begin{table}[htbp]",
        r"\centering",
        r"\scriptsize",
        r"\setlength{\tabcolsep}{3pt}",
        rf"\caption{{Tracer bullet, n = {n_val} val subjects, final checkpoint. Not a result.}}",
        r"\label{tab:tracer}",
        r"\begin{tabular}{rl" + "rrrrrr" * len(REGIONS) + "}",
        r"\toprule",
        " & & " + " & ".join(rf"\multicolumn{{6}}{{c}}{{{r}}}" for r in REGIONS) + r" \\",
        "".join(rf"\cmidrule(lr){{{3 + 6 * i}-{8 + 6 * i}}}" for i in range(len(REGIONS))),
        # headers on two rows keep the 18 number columns narrow enough for a landscape page
        "ID & Present & " + " & ".join(
            ["Dice & Dice & HD95 & HD95 & Both & One"] * len(REGIONS)) + r" \\",
        " & & " + " & ".join(
            ["mean & med. & mean & med. & empty & empty"] * len(REGIONS)) + r" \\",
        r"\midrule",
    ]
    for pid, pat in PATTERNS.items():
        cells = [str(pid), pat.name]
        for region in REGIONS:
            sel = [r for r in rows if int(r["pattern_id"]) == pid and r["region"] == region]
            assert len(sel) == n_val, f"pattern {pid} {region}: {len(sel)} rows, expected {n_val}"
            cells += cell_stats(sel)
        lines.append(" & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    return "\n".join(lines) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--run", required=True, type=Path)
    ap.add_argument("--out", type=Path, default=OUT)
    a = ap.parse_args(argv)
    tex = make(a.run)
    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_text(tex)
    print(f"wrote {a.out} (15 patterns x {len(REGIONS)} regions)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
