"""A compare folder -> three LaTeX files in writing/tables/ (spec 0005, AC-19).

    uv run python experiments/0005-strategies/make_table.py --compare <compare dir>
Writes 0005-strategies-<fold>-summary.tex, -dice.tex and -hd95.tex. No number is typed by hand.
Reads only summary.csv, patterns.csv and run.json of the compare folder. Exit 1, writing nothing,
unless run.json is there, its status is ok, and both CSVs are there with their row counts, checked
in that order. The three files compile through writing/tracer/e3e4-preview.tex.
"""
import argparse
import csv
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from common.data import REGIONS
from common.missing import PATTERNS
from common.runlog import load_run

REPO = Path(__file__).resolve().parents[2]
OUT = REPO / "writing" / "tables"
NOTE = {
    "val": ("Development fold, not a test result. Each checkpoint was chosen on this fold at "
            "complete input, so pattern 1 is slightly optimistic."),
    "test": "Test fold, opened once.",
}
METRICS = ("dice", "hd95_mm")
METRIC_LABEL = {"dice": "Dice", "hd95_mm": "HD95 (mm)"}
DECIMALS = {"dice": 3, "hd95_mm": 1}
COMPARISONS = ("E3-E1", "E4-E1", "E4-E3")
LEVELS = 4  # incomplete, missing_1, missing_2, missing_3
LEVEL = "incomplete"
STAR = "$^{*}$"


def finished_run(folder):
    """run.json of a finished comparison, checked before any CSV is read."""
    if not (Path(folder) / "run.json").is_file():
        raise SystemExit(f"ERROR: {Path(folder) / 'run.json'} missing")
    rec = load_run(folder)
    if rec.get("status") != "ok":
        raise SystemExit(f"ERROR: compare status is {rec.get('status')!r}, expected 'ok'")
    return rec


def read_rows(path, keys, expected):
    """A CSV as {key tuple: row}. Raises SystemExit if missing or on a wrong row count."""
    if not Path(path).is_file():
        raise SystemExit(f"ERROR: {path} missing")
    with open(path, newline="") as f:
        rows = {tuple(r[k] for k in keys): r for r in csv.DictReader(f)}
    if len(rows) != expected:
        raise SystemExit(f"ERROR: {len(rows)} rows in {Path(path).name}, expected {expected}")
    return rows


def read_summary(folder):
    """summary.csv as {(metric, region, level, comparison): row}."""
    return read_rows(Path(folder) / "summary.csv", ("metric", "region", "level", "comparison"),
                     len(METRICS) * len(REGIONS) * LEVELS * len(COMPARISONS))


def read_patterns(folder):
    """patterns.csv as {(metric, region, pattern_id, comparison): row}, pattern_id an int."""
    rows = read_rows(Path(folder) / "patterns.csv",
                     ("metric", "region", "pattern_id", "comparison"),
                     len(METRICS) * len(REGIONS) * len(PATTERNS) * len(COMPARISONS))
    return {(m, g, int(p), c): r for (m, g, p, c), r in rows.items()}


def star(row, alpha):
    return STAR if float(row["p_holm"]) < alpha else ""


def interval(row, places):
    return f"[{float(row['ci_low']):.{places}f}, {float(row['ci_high']):.{places}f}]"


def provenance(rec):
    return [("% generated by experiments/0005-strategies/make_table.py from runs "
             f"E1 {rec['e1_run_id']}, E3 {rec['e3_run_id']}, E4 {rec['e4_run_id']}"),
            f"% git {rec['git_commit']}, seed {rec['seed']}. Do not edit."]


def star_note(rec, against):
    """What a star means. The test is two sided, so the direction comes from mean_diff (AC-19)."""
    return (f" Star: Holm adjusted two sided p below {rec['alpha']:g} {against}, "
            "in either direction.")


def table(rec, what, name, columns, head, rows, note):
    """The shared booktabs layout. head and rows are lists of finished LaTeX lines."""
    fold = rec["fold"]
    return "\n".join([
        *provenance(rec),
        r"\begin{table}[htbp]",
        r"\centering",
        (rf"\caption{{{NOTE[fold]} {what}, {fold} fold, n = {rec['n_cases']}, "
         rf"seed {rec['seed']}.{note}}}"),
        rf"\label{{tab:strategies-{fold}-{name}}}",
        r"\resizebox{\linewidth}{!}{%",
        rf"\begin{{tabular}}{{{columns}}}",
        r"\toprule",
        *head,
        r"\midrule",
        *rows,
        r"\bottomrule",
        r"\end{tabular}%",
        "}",
        r"\end{table}",
    ]) + "\n"


def group_head(groups, span, first, sub):
    """The two header lines: one spanning label per group, then the column names."""
    spanning = " & ".join(rf"\multicolumn{{{span}}}{{c}}{{{g}}}" for g in groups)
    blank = " & ".join("" for _ in first)
    return [rf"{blank} & {spanning} \\", " & ".join([*first, *sub * len(groups)]) + r" \\"]


def summary_table(summary, rec):
    """The primary score: mean_diff with its star and CI, per comparison."""
    rows = []
    for m in METRICS:
        places = DECIMALS[m]
        for g in REGIONS:
            cells = []
            for c in COMPARISONS:
                row = summary[m, g, LEVEL, c]
                cells += [f"{float(row['mean_diff']):+.{places}f}{star(row, rec['alpha'])}",
                          interval(row, places)]
            rows.append(" & ".join([METRIC_LABEL[m], g, *cells]) + r" \\")
    return table(rec, "Paired difference of the mean over the 14 incomplete patterns", "summary",
                 "ll" + "rr" * len(COMPARISONS),
                 group_head(COMPARISONS, 2, ["Metric", "Region"], ["Diff", "CI"]), rows,
                 star_note(rec, "over the 3 comparisons"))


def pattern_table(patterns, rec, metric, stat, what, name):
    """stat of E1, E3 and E4 per pattern and region. A star on E3 or E4 is its test against E1."""
    places = DECIMALS[metric]
    rows = []
    for p, pattern in PATTERNS.items():
        cells = []
        for g in REGIONS:
            e3, e4 = patterns[metric, g, p, "E3-E1"], patterns[metric, g, p, "E4-E1"]
            cells += [f"{float(e3[f'{stat}_second']):.{places}f}",
                      f"{float(e3[f'{stat}_first']):.{places}f}{star(e3, rec['alpha'])}",
                      f"{float(e4[f'{stat}_first']):.{places}f}{star(e4, rec['alpha'])}"]
        rows.append(" & ".join([str(p), pattern.name, *cells]) + r" \\")
    return table(rec, what, name, "rl" + "rrr" * len(REGIONS),
                 group_head(REGIONS, 3, ["ID", "Present"], ["E1", "E3", "E4"]), rows,
                 star_note(rec, "against E1"))


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--compare", required=True, type=Path)
    ap.add_argument("--out-dir", type=Path, default=OUT)
    a = ap.parse_args(argv)
    rec = finished_run(a.compare)
    summary, patterns = read_summary(a.compare), read_patterns(a.compare)
    files = {"summary": summary_table(summary, rec),
             "dice": pattern_table(patterns, rec, "dice", "mean",
                                   "Mean Dice of each model under each pattern", "dice"),
             "hd95": pattern_table(patterns, rec, "hd95_mm", "median",
                                   "Median HD95 in mm of each model under each pattern", "hd95")}
    a.out_dir.mkdir(parents=True, exist_ok=True)
    for name, tex in files.items():
        path = a.out_dir / f"0005-strategies-{rec['fold']}-{name}.tex"
        path.write_text(tex)
        print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
