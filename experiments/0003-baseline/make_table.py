"""metrics_val.csv of one E1 run -> writing/tables/0003-baseline-val.tex (spec 0003, AC-14).

    uv run python experiments/0003-baseline/make_table.py --run <run dir>
Reads only the run's metrics_val.csv and run.json. No number is typed by hand.
Exit 1 if metrics_val.csv is missing or has the wrong row count.
"""
import argparse
import csv
import statistics
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from common.data import REGIONS
from common.runlog import load_run

REPO = Path(__file__).resolve().parents[2]
OUT = REPO / "writing" / "tables" / "0003-baseline-val.tex"


def region_stats(rows):
    """Dice mean, Dice median, HD95 mean, HD95 median, both empty count, one empty count.

    Both empty: truth and prediction empty (scored Dice 1, HD95 0). One empty: exactly one side
    empty (scored Dice 0, HD95 at the empty rule value). The HD95 statistics include those values.
    """
    dice = [float(r["dice"]) for r in rows]
    hd = [float(r["hd95_mm"]) for r in rows]
    n_empty = [(r["gt_empty"] == "True") + (r["pred_empty"] == "True") for r in rows]
    return (f"{statistics.mean(dice):.3f}", f"{statistics.median(dice):.3f}",
            f"{statistics.mean(hd):.1f}", f"{statistics.median(hd):.1f}",
            str(n_empty.count(2)), str(n_empty.count(1)))


def make(run_dir):
    rec = load_run(run_dir)
    n_val = len(rec["val_cases"])
    path = Path(run_dir) / "metrics_val.csv"
    if not path.is_file():
        raise SystemExit(f"ERROR: {path} missing")
    with open(path, newline="") as f:
        rows = list(csv.DictReader(f))
    expected = n_val * len(REGIONS)
    if len(rows) != expected:
        raise SystemExit(f"ERROR: {len(rows)} rows in metrics_val.csv, expected {expected}")

    lines = [
        f"% generated by experiments/0003-baseline/make_table.py from run {rec['run_id']}",
        f"% config {rec['config_hash']}, git {rec['git_commit']}, seed {rec['seed']}. Do not edit.",
        r"\begin{table}[htbp]",
        r"\centering",
        (rf"\caption{{Complete input baseline, validation fold (development), n = {n_val}, "
         rf"seed {rec['seed']}, checkpoint at iteration {rec['best_iteration']}. "
         r"Not a test result.}"),
        r"\label{tab:baseline-val}",
        r"\begin{tabular}{lrrrrrr}",
        r"\toprule",
        r"Region & Dice mean & Dice median & HD95 mean & HD95 median & Both empty & One empty \\",
        r"\midrule",
    ]
    for region in REGIONS:
        sel = [r for r in rows if r["region"] == region]
        assert len(sel) == n_val, f"{region}: {len(sel)} rows, expected {n_val}"
        lines.append(" & ".join([region, *region_stats(sel)]) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    return "\n".join(lines) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--run", required=True, type=Path)
    ap.add_argument("--out", type=Path, default=OUT)
    a = ap.parse_args(argv)
    tex = make(a.run)
    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_text(tex)
    print(f"wrote {a.out} ({len(REGIONS)} regions)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
